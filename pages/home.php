<p>
<h2>🌟  🌟  🌟  Bienvenue  ! 🌟  🌟  🌟</h2>
<strong>Notre site vous ouvre les portes d'un univers où la lecture rime avec plaisir et découverte.</strong><br>
<br>
<br>

La Médiathèque des Enfants a pour vocation d'offrir aux jeunes de 0 à 14 ans — et à leurs familles — un accès libre et joyeux à la culture sous toutes ses formes : CD , DVD ,films, apprentissage de francais orthographe et musique et jeux de société. Ce site a été créé pour prolonger cette expérience au-delà de nos murs : il permet de découvrir nos collections, de connaître nos animations (heures du conte, ateliers créatifs, après-midis jeux), de préparer sa visite en toute simplicité.

Plus qu'un simple outil pratique, ce site se veut un compagnon de lecture : un espace où parents et enfants trouvent des idées, des conseils et l'envie de pousser la porte de la médiathèque. C'est grandir, rêver et partager — et que cela commence dès le plus jeune âge.



